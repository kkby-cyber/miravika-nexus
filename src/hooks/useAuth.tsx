import { useEffect, useState } from "react";
import type { Session, User } from "@supabase/supabase-js";
import { supabase } from "@/integrations/supabase/client";

export type AppRole = "SUPER_ADMIN" | "ADMIN" | "ORDER_MANAGER" | "CATALOG_MANAGER";

export function useAuth() {
  const [session, setSession] = useState<Session | null>(null);
  const [user, setUser] = useState<User | null>(null);
  const [roles, setRoles] = useState<AppRole[]>([]);
  const [loading, setLoading] = useState(true);

  useEffect(() => {
    const { data: sub } = supabase.auth.onAuthStateChange((_event, next) => {
      setSession(next);
      setUser(next?.user ?? null);
      if (!next?.user) {
        setRoles([]);
        setLoading(false);
      }
    });

    supabase.auth.getSession().then(({ data }) => {
      setSession(data.session);
      setUser(data.session?.user ?? null);
      if (!data.session?.user) setLoading(false);
    });

    return () => sub.subscription.unsubscribe();
  }, []);

  useEffect(() => {
    if (!user) return;
    let cancelled = false;
    setLoading(true);
    supabase
      .from("user_roles")
      .select("role")
      .eq("user_id", user.id)
      .then(({ data }) => {
        if (cancelled) return;
        setRoles((data ?? []).map((r) => r.role as AppRole));
        setLoading(false);
      });
    return () => {
      cancelled = true;
    };
  }, [user]);

  const isStaff = roles.length > 0;
  const can = {
    catalog: roles.some((r) => ["SUPER_ADMIN", "ADMIN", "CATALOG_MANAGER"].includes(r)),
    orders: roles.some((r) => ["SUPER_ADMIN", "ADMIN", "ORDER_MANAGER"].includes(r)),
    settings: roles.some((r) => ["SUPER_ADMIN", "ADMIN"].includes(r)),
    roles: roles.includes("SUPER_ADMIN"),
  };

  return { session, user, roles, isStaff, can, loading };
}
